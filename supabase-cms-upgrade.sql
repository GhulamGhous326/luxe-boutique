-- ---------- Auto-increment product ids (safe if already set) ----------
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_name = 'products' and column_name = 'id' and is_identity = 'YES'
  ) then
    alter table products alter column id add generated by default as identity;
  end if;
end $$;

select setval(pg_get_serial_sequence('products', 'id'), coalesce(max(id), 0)) from products;

-- ---------- Promo codes ----------
create table if not exists promos (
  code text primary key,
  percent numeric not null,
  active boolean not null default true
);
alter table promos enable row level security;

drop policy if exists "public read promos" on promos;
create policy "public read promos" on promos
  for select to anon using (active = true);

drop policy if exists "admin all promos" on promos;
create policy "admin all promos" on promos
  for all to authenticated using (true) with check (true);

insert into promos (code, percent, active) values ('WELCOME10', 0.10, true)
on conflict (code) do nothing;

-- ---------- Site settings (announcement, hero text, sale) ----------
create table if not exists settings (
  key text primary key,
  value text not null default ''
);
alter table settings enable row level security;

drop policy if exists "public read settings" on settings;
create policy "public read settings" on settings
  for select to anon using (true);

drop policy if exists "admin all settings" on settings;
create policy "admin all settings" on settings
  for all to authenticated using (true) with check (true);

insert into settings (key, value) values
  ('announcement', 'The Winter Edit — Flat 25% Off'),
  ('hero_eyebrow', 'Maison de Luxe — Est. 2026'),
  ('hero_line1', 'Timeless'),
  ('hero_line2', 'Elegance,'),
  ('hero_line3', 'Worn Daily'),
  ('sale_enabled', '1'),
  ('sale_ends_at', '')
on conflict (key) do nothing;

-- ---------- Product image storage ----------
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "public read images" on storage.objects;
create policy "public read images" on storage.objects
  for select using (bucket_id = 'product-images');

drop policy if exists "admin upload images" on storage.objects;
create policy "admin upload images" on storage.objects
  for insert to authenticated with check (bucket_id = 'product-images');

drop policy if exists "admin delete images" on storage.objects;
create policy "admin delete images" on storage.objects
  for delete to authenticated using (bucket_id = 'product-images');
